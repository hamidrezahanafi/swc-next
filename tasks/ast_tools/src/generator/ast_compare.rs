use convert_case::{Case, Casing};
use proc_macro2::TokenStream;
use quote::quote;

use crate::{
    output::{RawOutput, RustOutput},
    schema::{AstType, Schema},
    util::safe_ident,
};

/// Generate the conformance comparator from the same schema as the AST APIs.
/// New nodes and fields must participate without maintaining a second AST model.
pub fn ast_compare(schema: &Schema) -> RawOutput {
    let mut impls = TokenStream::new();
    let mut arms = TokenStream::new();
    for ty in &schema.types {
        let name = ty.expr_ident(schema);
        let left_ty = ty
            .repr_ident(schema)
            .to_string()
            .replace("'id", "'left")
            .parse::<TokenStream>()
            .unwrap();
        let right_ty = ty
            .repr_ident(schema)
            .to_string()
            .replace("'id", "'right")
            .parse::<TokenStream>()
            .unwrap();
        match ty {
            AstType::Struct(node) => {
                let mut fields = TokenStream::new();
                for field in &node.fields {
                    // Spelling can change without changing a literal's value.
                    // Other raw text (notably tagged templates) is significant.
                    if field.name == "raw"
                        && matches!(node.name.as_str(), "StringLiteral" | "NumericLiteral")
                    {
                        continue;
                    }
                    let getter = safe_ident(&field.name.to_case(Case::Snake));
                    let path = format!("{}.{}", node.name, field.name);
                    let comparison = match (node.name.as_str(), field.name.as_str()) {
                        ("BigIntLiteral", "raw") => {
                            quote!(super::compare_bigint(left, right, asts))
                        }
                        _ => quote!(left.compare(right, asts)),
                    };
                    fields.extend(quote! {
                        let left = self.#getter(asts.left);
                        let right = other.#getter(asts.right);
                        #comparison.map_err(|error| format!("{}.{error}", #path))?;
                    });
                }
                impls.extend(quote! {
                    impl<'left, 'right> Compare<'left, 'right, #right_ty> for #left_ty {
                        fn compare(self, other: #right_ty, asts: &AstPair<'_, '_, 'left, 'right>) -> Result<(), String> {
                            #fields
                            Ok(())
                        }
                    }
                });
                arms.extend(quote! {
                    (NodeKindData::#name(left), NodeKindData::#name(right)) => left.compare(right, asts),
                });
            }
            AstType::Enum(_) => {
                impls.extend(quote! {
                    impl<'left, 'right> Compare<'left, 'right, #right_ty> for #left_ty {
                        fn compare(self, other: #right_ty, asts: &AstPair<'_, '_, 'left, 'right>) -> Result<(), String> {
                            asts.nodes(self.node_id(), other.node_id())
                        }
                    }
                });
            }
            AstType::Primitive(primitive) => {
                if matches!(primitive.name, "AstUtf8" | "AstWtf8" | "f64" | "Span") {
                    continue;
                }
                impls.extend(quote! { compare_value!(#name); });
            }
            _ => {}
        }
    }

    RustOutput {
        path: "tasks/testsuite/src/ast_compare/generated.rs".into(),
        tokens: quote! {
            //! Generated by ast_tools. Do not edit by hand.
            #![allow(unused_variables)]
            use swc_next_ecma_ast::*;
            use super::{AstPair, Compare, compare_value};

            #impls

            pub(super) fn compare_nodes<'left, 'right>(left: NodeKindData<'left>, right: NodeKindData<'right>, asts: &AstPair<'_, '_, 'left, 'right>) -> Result<(), String> {
                match (left, right) {
                    #arms
                    _ => Err(format!("node kind: {:?} != {:?}", asts.left.node_kind(left.node_id()), asts.right.node_kind(right.node_id()))),
                }
            }
        },
    }.into()
}
